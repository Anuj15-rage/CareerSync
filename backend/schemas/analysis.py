class SanitizedProjectItem(BaseModel):
    """Sanitized project record with PII scrubbed and bounded lengths."""
    model_config = ConfigDict(from_attributes=True, extra="forbid")

    title: str = Field(..., min_length=1, max_length=150)
    technologies: Optional[str] = Field(None, max_length=250)
    description: Optional[str] = Field(None, max_length=1000)


class SanitizedExperienceItem(BaseModel):
    """Sanitized experience record with PII scrubbed and bounded lengths."""
    model_config = ConfigDict(from_attributes=True, extra="forbid")

    role_title: str = Field(..., min_length=1, max_length=150)
    duration: Optional[str] = Field(None, max_length=100)
    description: Optional[str] = Field(None, max_length=1000)


class SanitizedResumePayload(BaseModel):
    """
    Strict, privacy-sanitized payload representing candidate qualifications
    ready for transmission to the LLM. Strictly excludes candidate name, email,
    phone, raw resume text, file bytes, and tokens.
    """
    model_config = ConfigDict(from_attributes=True, extra="forbid")

    target_role_title: Optional[str] = Field(None, max_length=150)
    skills: List[str] = Field(default_factory=list, max_length=100)
    projects: List[SanitizedProjectItem] = Field(default_factory=list, max_length=20)
    experience: List[SanitizedExperienceItem] = Field(default_factory=list, max_length=20)
    missing_skills: List[str] = Field(default_factory=list, max_length=50)

