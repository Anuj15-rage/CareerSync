def _strip_additional_properties_from_schema(schema: dict) -> None:
    """
    Remove 'additionalProperties' from the generated JSON schema.
    The Gemini Developer API does not support 'additional_properties' in response_schema.
    """
    schema.pop("additionalProperties", None)


class ResumeImprovementItem(BaseModel):
    """
    Individual actionable improvement suggestion generated by Gemini.
    Enforces strict typing, length boundaries, and database-compatible ENUMs.
    """
    model_config = ConfigDict(
        from_attributes=True,
        extra="forbid",
        json_schema_extra=_strip_additional_properties_from_schema,
    )

    category: ImprovementCategory = Field(
        ...,
        description="Category matching database ENUM (STRUCTURE, PROJECTS, EXPERIENCE, SKILLS_FORMATTING, KEYWORDS)",
    )
    priority: SuggestionPriority = Field(
        default=SuggestionPriority.MEDIUM,
        description="Priority level (HIGH, MEDIUM, LOW)",
    )
    title: str = Field(
        ...,
        min_length=3,
        max_length=150,
        description="Concise summary title of the improvement area",
    )
    description: str = Field(
        ...,
        min_length=10,
        max_length=1000,
        description="Detailed explanation of the observation or area needing enhancement",
    )
    actionable_recommendation: str = Field(
        ...,
        min_length=10,
        max_length=1000,
        description="Concrete, actionable advice on how to improve the resume without fabricating qualifications",
    )


class ResumeImprovementResponse(BaseModel):
    """
    Top-level response envelope for resume improvement suggestions.
    Guarantees strict type safety and structure.
    """
    model_config = ConfigDict(
        from_attributes=True,
        extra="forbid",
        json_schema_extra=_strip_additional_properties_from_schema,
    )

    resume_id: int = Field(..., gt=0, description="Unique resume identifier")
    session_id: Optional[int] = Field(None, gt=0, description="Associated analysis session ID if persisted")
    target_role_id: Optional[int] = Field(None, gt=0, description="Target job role ID evaluated")
    target_role_title: Optional[str] = Field(None, max_length=150, description="Target job role title evaluated")
    total_suggestions: int = Field(..., ge=0, description="Total count of improvement suggestions")
    suggestions: List[ResumeImprovementItem] = Field(
        default_factory=list,
        max_length=50,
        description="List of structured improvement suggestions",
    )
    message: Optional[str] = Field(None, max_length=255, description="Summary or status message")
    generated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when suggestions were generated",
    )


